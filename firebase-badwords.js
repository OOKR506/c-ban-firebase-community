// 텍스트 정규화: 소문자 + 공백/특수문자/제로폭 문자 제거 (한글·영문·숫자·ㄱ-ㅎ 유지)
function normalizeForBadWord(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[​-‍﻿]/g, '')
    .replace(/[^0-9a-z가-힣ㄱ-ㅎㅏ-ㅣ]/g, '')
    .replace(/(.)\1{2,}/g, '$1$1'); // 같은 글자 3번 이상 반복은 2번으로
}

// 미리 정규화된 금지어 테이블 생성
const _BAD_TABLE = BAD_WORD_LIST.map(g => ({
  category: g.category,
  words: g.words.map(w => ({ raw: w, norm: normalizeForBadWord(w) })).filter(w => w.norm.length >= 2)
}));

/**
 * 금지어 검사
 * @returns {{blocked:boolean, word?:string, category?:string}}
 */
function checkBadWords(text) {
  let norm = normalizeForBadWord(text);
  if (!norm) return { blocked: false };
  // 정상 단어 제거 (오탐 방지)
  BAD_WORD_WHITELIST.forEach(w => {
    const n = normalizeForBadWord(w);
    if (n) norm = norm.split(n).join('');
  });
  // 한글 사이에 숫자/영문을 끼워 넣는 우회(예: 시1발, 시a발)도 잡기 위한 두 번째 문자열
  const normKo = norm.replace(/[0-9a-z]/g, '');
  for (const g of _BAD_TABLE) {
    for (const w of g.words) {
      if (norm.includes(w.norm)) return { blocked: true, word: w.raw, category: g.category };
      if (/[가-힣ㄱ-ㅎ]/.test(w.norm) && normKo.length >= 2 && normKo.includes(w.norm.replace(/[0-9a-z]/g, '')) && w.norm.replace(/[0-9a-z]/g, '').length >= 2) {
        return { blocked: true, word: w.raw, category: g.category };
      }
    }
  }
  return { blocked: false };
}

// 여러 문자열(제목+내용 등)을 한 번에 검사
function checkBadWordsMulti(...texts) {
  for (const t of texts) {
    const r = checkBadWords(t);
    if (r.blocked) return r;
  }
  return { blocked: false };
}

